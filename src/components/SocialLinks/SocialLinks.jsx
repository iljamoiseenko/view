const LABELS = {
  website: 'Website',
  instagram: 'Instagram',
  facebook: 'Facebook',
  tiktok: 'TikTok',
  threads: 'Threads',
  telegram: 'Telegram',
  youtube: 'YouTube',
}

export default function SocialLinks({ place }) {
  if (!place) return null

  const links = [
    { key: 'website', url: place.website },
    { key: 'instagram', url: place.instagramUrl },
    { key: 'facebook', url: place.facebookUrl },
    { key: 'tiktok', url: place.tiktokUrl },
    { key: 'threads', url: place.threadsUrl },
    { key: 'telegram', url: place.telegramUrl },
    { key: 'youtube', url: place.youtubeUrl },
  ].filter(l => l.url)

  if (links.length === 0) return null

  return (
    <div className="social-links">
      {links.map(l => (
        <a
          key={l.key}
          href={l.url}
          target="_blank"
          rel="noreferrer"
          className="social-links__item"
          aria-label={LABELS[l.key]}
          title={LABELS[l.key]}
        >
          {ICONS[l.key]}
        </a>
      ))}
    </div>
  )
}
